"""Generate ``catalogue.pyi`` from ``catalogue.toml``.

The stub declares the type of every name the lazy runtime catalogue can
produce, so type checkers and editors know about them without anything being
built at runtime. The unit kinds are not hand-maintained: one base unit per
definition is built and its resolved ``kind`` is used for every prefixed
variant (prefixes never change the dimension).

Usage::

    python -m units_lib.unit.generate_catalogue           # (re)write the stub
    python -m units_lib.unit.generate_catalogue --check   # exit 1 if it is stale
"""

from __future__ import annotations

import argparse
from collections import defaultdict
from pathlib import Path

from units_lib.unit import catalogue
from units_lib.unit.affine_unit import AffineUnit
from units_lib.unit.catalogue_spec import build_index, load_specs

HEADER = '''\
"""Type stub for `units_lib.catalogue`.

This file is generated by `generate_catalogue.py` from `catalogue.toml`.
Do not edit manually.
"""

'''


def stub_path() -> Path:
    return Path(catalogue.__file__).with_suffix(".pyi")


def render_stub() -> str:
    """Build the full text of the stub."""
    specs = load_specs()
    units_catalogue = build_index(specs)

    kind_imports: dict[str, set[str]] = defaultdict(set)
    unit_types: dict[str, str] = {}
    unit_kinds: dict[str, str] = {}
    uses_unit = False
    uses_affine = False

    for unit_name in units_catalogue:
        unit = getattr(catalogue, unit_name)
        if isinstance(unit, AffineUnit):
            unit_types[unit_name] = "AffineUnit"
            uses_affine = True
        else:
            unit_types[unit_name] = "Unit"
            uses_unit = True

        kind = unit.kind
        if kind is None:
            raise ValueError(f"No kind defined for unit {unit_name}")

        kind_imports[kind.__module__].add(kind.__qualname__)
        unit_kinds[unit_name] = kind.__qualname__

    imports: list[str] = []
    for module in sorted(kind_imports):
        names = ",\n    ".join(sorted(kind_imports[module]))
        imports.append(f"from {module} import (\n    {names},\n)")
    if uses_affine:
        imports.append("from units_lib.unit.affine_unit import AffineUnit")
    if uses_unit:
        imports.append("from units_lib.unit.unit import Unit")

    lines = [
        f"{name}: {unit_types[name]}[{unit_kinds[name]}]"
        for name in sorted(units_catalogue)
    ]
    return HEADER + "\n".join(imports) + "\n\n" + "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Generate ``catalogue.pyi`` from ``catalogue.toml``."
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="do not write; exit with status 1 if the stub is out of date",
    )
    args = parser.parse_args(argv)

    path = stub_path()
    stub = render_stub()

    if args.check:
        current = path.read_text(encoding="utf-8") if path.exists() else ""
        if current != stub:
            print(
                f"{path} is out of date; run `python -m units_lib.generate_catalogue`"
            )
            return 1
        print(f"{path} is up to date")
        return 0

    path.write_text(stub, encoding="utf-8", newline="\n")
    print(f"Wrote {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
