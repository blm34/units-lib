from fractions import Fraction
from pathlib import Path

import units_lib.si_prefix as prefix
from units_lib.dimensions.dimensions import BaseDimension, Dimension
from units_lib.si_prefix import SIPrefix, iter_prefixes
from units_lib.unit.catalogue import *
from units_lib.unit.unit import NamedUnit, Unit, UnitTerm

UNITS = {}
LINES = []


def name_new_unit(
    name: str,
    symbol: str,
    dimension: Dimension,
    scale: Fraction = Fraction(1),
    min_prefix: SIPrefix = prefix.QUECTO,
    max_prefix: SIPrefix = prefix.QUETTA,
):
    named_unit = NamedUnit(
        name=name,
        symbol=symbol,
        dimension=dimension,
        ref_scale=scale,
    )
    _create_unit_from_named_unit(named_unit, min_prefix, max_prefix)
    return UNITS[name]


def derive_new_unit(
    name: str,
    symbol: str,
    expr: Unit,
    scale: Fraction = Fraction(1),
    min_prefix: SIPrefix = prefix.QUECTO,
    max_prefix: SIPrefix = prefix.QUETTA,
):
    named_unit = NamedUnit(
        name=name,
        symbol=symbol,
        dimension=expr.dimension,
        ref_scale=expr.scale * scale,
    )
    _create_unit_from_named_unit(named_unit, min_prefix, max_prefix)
    return UNITS[name]


def _create_unit_from_named_unit(
    named_unit: NamedUnit,
    min_prefix: SIPrefix,
    max_prefix: SIPrefix,
):
    for _prefix in iter_prefixes(min_prefix, max_prefix):
        unit_term = UnitTerm(named_unit, _prefix)
        unit = Unit((unit_term,))

        unit_name = unit_term.name

        UNITS[unit_name] = unit
        LINES.append(f"{unit_name} = {unit!r}")
    LINES.append("")


