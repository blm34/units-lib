"""Generate ``catalogue.pyi`` from ``catalogue.toml``."""

from __future__ import annotations

import argparse
from pathlib import Path

from units_lib.kind.catalogue import catalogue
from units_lib.kind.catalogue.catalogue_spec import load_specs, validate

HEADER = '''\
"""Type stub for `units_lib.kind.catalogue.catalogue`.

This file is generated by `generate_kind_catalogue.py` from `catalogue.toml`.
Do not edit manually.
"""

from units_lib.kind.real_kind import RealKind

'''


def stub_path() -> Path:
    return Path(catalogue.__file__).with_suffix(".pyi")


def render_stub() -> str:
    """Build the full text of the stub."""
    registry = load_specs()

    validate(registry)

    lines = []
    added: set[str] = set()

    def add(name: str):
        if name in added:
            return

        spec = registry.get(name)
        assert spec is not None

        if spec.alias is not None:
            add(spec.alias)
            lines.append(f"\n{spec.name} = {spec.alias}\n")
        elif spec.inherits is not None:
            add(spec.inherits)
            lines.append(f"class {spec.name}({spec.inherits}): ...")
        else:
            lines.append(f"class {spec.name}(RealKind): ...")
        added.add(spec.name)

    for name in registry.all_names():
        if name in added:
            continue

        add(name)

    return HEADER + "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Generate `catalogue.pyi` from `catalogue.toml`."
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="do not write; exit with status 1 if the stub is out of date",
    )
    args = parser.parse_args(argv)

    path = stub_path()
    stub = render_stub()

    if args.check:
        current = path.read_text(encoding="utf-8") if path.exists() else ""
        if current != stub:
            print(f"{path} is out of date; run `generate-kind-catalogue`")
            return 1
        print(f"{path} is up to date")
        return 0

    path.write_text(stub, encoding="utf-8", newline="\n")
    print(f"Wrote {path}")
    return 0
