from __future__ import annotations

from collections import defaultdict
from typing import ClassVar

from .dimensions import BaseDimension, Dimension

_registry: dict[Dimension, list[type[Kind]]] = defaultdict(list)
_defaults: dict[Dimension, type[Kind]] = {}


class Kind:
    """The kind of a quantity."""

    dimension: ClassVar[Dimension]
    name: ClassVar[str]

    def __init_subclass__(
        cls,
        dim: Dimension,
        default: bool = False,
        **kw,
    ):
        """Set the `dimension` class variable, and add dimension to the registry."""
        super().__init_subclass__(**kw)

        if default and dim in _defaults:
            raise TypeError(
                f"{_defaults[dim].__name__} is already the default `Kind` "
                f"for {dim}; cannot also make {cls.__name__} the default."
            )

        cls.dimension = dim
        cls.name = cls.__name__
        _registry[dim].append(cls)

        if default:
            _defaults[dim] = cls


def kinds_for(dim: Dimension) -> tuple[type[Kind], ...]:
    """All `Kind`s sharing the given dimension."""
    return tuple(_registry.get(dim, ()))


def resolve_kind(dim: Dimension) -> type[Kind] | None:
    """Get the default `Kind` for the given dimension."""
    kinds = kinds_for(dim)
    if len(kinds) == 1:
        return kinds[0]

    return _defaults.get(dim)


def get_common_kind(a:type[Kind], b:type[Kind]) -> type[Kind] | None:
    """Get the lowest possible kind that both `a` and `b` inherit from."""
    lowest_common_ancestor = None

    for cls in b.__mro__:
        if cls == Kind:
            break

        if cls in a.__mro__:
            lowest_common_ancestor = cls
            break

    return lowest_common_ancestor


_DIMENSIONLESS = Dimension.dimensionless()
_TIME = Dimension.base(BaseDimension.TIME)
_LENGTH = Dimension.base(BaseDimension.LENGTH)
_MASS = Dimension.base(BaseDimension.MASS)
_ELECTRIC_CURRENT = Dimension.base(BaseDimension.ELECTRIC_CURRENT)
_TEMPERATURE = Dimension.base(BaseDimension.TEMPERATURE)
_AMOUNT_OF_SUBSTANCE = Dimension.base(BaseDimension.AMOUNT_OF_SUBSTANCE)
_LUMINOUS_INTENSITY = Dimension.base(BaseDimension.LUMINOUS_INTENSITY)

# fmt: off

# Dimensionless
class Dimensionless(Kind, dim=_DIMENSIONLESS): ...
class Angle(Kind, dim=_DIMENSIONLESS): ...
class SolidAngle(Kind, dim=_DIMENSIONLESS): ...

# SI Base Dimensions
class Time(Kind, dim=_TIME): ...
class Length(Kind, dim=_LENGTH): ...
class Mass(Kind, dim=_MASS): ...
class ElectricCurrent(Kind, dim=_ELECTRIC_CURRENT): ...
class Temperature(Kind, dim=_TEMPERATURE): ...
class AmountOfSubstance(Kind, dim=_AMOUNT_OF_SUBSTANCE): ...
class LuminousIntensity(Kind, dim=_LUMINOUS_INTENSITY): ...

# Derived Dimensions
class Frequency(Kind, dim=_DIMENSIONLESS/ _TIME): ...
class Radioactivity(Kind, dim=_DIMENSIONLESS/ _TIME): ...

class Area(Kind, dim=_LENGTH**2): ...
class Volume(Kind, dim=_LENGTH**3): ...

class Velocity(Kind, dim=_LENGTH / _TIME): ...
class Acceleration(Kind, dim=Velocity.dimension / _TIME): ...
class Jerk(Kind, dim=Acceleration.dimension / _TIME): ...
class Snap(Kind, dim=Jerk.dimension / _TIME, default=True): ...
class Jounce(Snap, dim=Snap.dimension): ...
class Crackle(Kind, dim=Snap.dimension / _TIME): ...
class Pop(Kind, dim=Crackle.dimension / _TIME): ...

class Force(Kind, dim=_MASS * Acceleration.dimension): ...
class Energy(Kind, dim=_MASS * Velocity.dimension ** 2): ...
class Work(Energy, dim=Force.dimension * _LENGTH): ...
class Torque(Kind, dim=Force.dimension * _LENGTH): ...
class AmountOfHeat(Energy, dim=Energy.dimension): ...
class Power(Kind, dim=Energy.dimension / _TIME, default=True): ...
class RadiantFlux(Power, dim=Power.dimension): ...
class Intensity(Kind, dim=Power.dimension / Area.dimension): ...
class Pressure(Kind, dim=Force.dimension / Area.dimension): ...
class Stress(Kind, dim=Force.dimension / Area.dimension): ...

class ElectricCharge(Kind, dim=_TIME * _ELECTRIC_CURRENT): ...
class ElectricPotentialDifference(Kind, dim=Power.dimension / _ELECTRIC_CURRENT): ...
class ElectricResistance(Kind, dim=ElectricPotentialDifference.dimension / _ELECTRIC_CURRENT): ...
class ElectricConductance(Kind, dim=_DIMENSIONLESS / ElectricResistance.dimension): ...
class Capacitance(Kind, dim=ElectricCharge.dimension / ElectricPotentialDifference.dimension): ...

class MagneticFlux(Kind, dim=ElectricPotentialDifference.dimension * _TIME): ...
class MagneticFluxDensity(Kind, dim=MagneticFlux.dimension / Area.dimension): ...
class Inductance(Kind, dim=MagneticFlux.dimension / _ELECTRIC_CURRENT): ...

class LuminousFlux(Kind, dim=_LUMINOUS_INTENSITY): ...
class Illuminance(Kind, dim=_LUMINOUS_INTENSITY / Area.dimension): ...

class AbsorbedDose(Kind, dim=Energy.dimension / _MASS): ...
class Kerma(Kind, dim=Energy.dimension / _MASS): ...
class DoseEquivalent(Kind, dim=Energy.dimension / _MASS): ...

class CatalyticActivity(Kind, dim=_AMOUNT_OF_SUBSTANCE / _TIME): ...

